#!/usr/bin/env node
/**
 * 从完整 legacy 源码生成无 steps 的 lite 版本（供未来 subPackage 主包瘦身）。
 * 当前 catalogLoader 仍用 legacyFullLoader 静态加载完整 legacy。
 * 运行：npm run build:legacy-lite
 */
import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()

function stripRecipeFields(source) {
  let out = source
  out = out.replace(/steps:\s*\[[\s\S]*?\],?\n/g, '')
  out = out.replace(/nutritionAnalysis:\s*'[^']*',?\n/g, '')
  out = out.replace(/nutritionAnalysis:\s*"[^"]*",?\n/g, '')
  return out
}

const srcPath = path.join(root, 'src/data/recipesLegacy.ts')
const src = fs.readFileSync(srcPath, 'utf8')
const header = src.slice(0, src.indexOf('export const RAW'))
const bodyStart = src.indexOf('export const RAW')
const body = src.slice(bodyStart).replace('export const RAW', 'export const RAW_LITE')
const out = `${header}/**\n * AUTO-GENERATED by scripts/build-legacy-lite.mjs — do not edit.\n */\n${stripRecipeFields(body)}`
fs.writeFileSync(path.join(root, 'src/data/recipesLegacyLite.ts'), out)
console.log('Wrote src/data/recipesLegacyLite.ts')
